export function formatDate(iso: string, locale: Locale, opts: Intl.DateTimeFormatOptions = {}) {
  const out = new Date(iso.length === 10 ? iso + "T12:00:00Z" : iso).toLocaleDateString(locale === "en" ? "en-US" : "es-AR", {
    weekday: "long",
    day: "numeric",
    month: "long",
    timeZone: iso.length === 10 ? "UTC" : "America/New_York",
    ...opts,
  });
  return out.charAt(0).toUpperCase() + out.slice(1);
}
